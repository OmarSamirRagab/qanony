#!/usr/bin/env node
/**
 * Generates src/types/database.ts (supabase-js `Database` type) by applying the
 * migrations to an in-process PGlite instance and introspecting the catalog.
 * Equivalent in shape to `supabase gen types typescript`, without Docker.
 */
import { PGlite } from '@electric-sql/pglite'
import { btree_gist } from '@electric-sql/pglite/contrib/btree_gist'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const db = new PGlite({ extensions: { btree_gist } })
await db.exec(readFileSync(path.join(root, 'tests/helpers/supabase-shim.sql'), 'utf8'))
for (const f of readdirSync(path.join(root, 'supabase/migrations')).filter((f) => f.endsWith('.sql')).sort()) {
  await db.exec(readFileSync(path.join(root, 'supabase/migrations', f), 'utf8'))
}

const SCHEMA = 'public'
const enums = (await db.query(
  `select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
     from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = $1 group by t.typname order by t.typname`, [SCHEMA])).rows
const enumNames = new Set(enums.map((e) => e.name))

function tsType(udt, isArray = false) {
  if (isArray || udt.startsWith('_')) return `${tsType(udt.replace(/^_/, ''))}[]`
  if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`
  switch (udt) {
    case 'int2': case 'int4': case 'int8': case 'float4': case 'float8': case 'numeric': case 'oid': return 'number'
    case 'bool': return 'boolean'
    case 'json': case 'jsonb': return 'Json'
    case 'void': return 'undefined'
    case 'record': return 'Record<string, unknown>'
    default: return 'string'
  }
}

const tables = (await db.query(
  `select c.relname as name, c.relkind as kind from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = $1 and c.relkind in ('r', 'v') order by c.relname`, [SCHEMA])).rows

const columns = (await db.query(
  `select c.relname as table, a.attname as name, t.typname as udt, a.attnotnull as notnull,
          a.atthasdef as hasdef, a.attidentity as identity, a.attgenerated as generated
     from pg_attribute a join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace
     join pg_type t on t.oid = a.atttypid
    where n.nspname = $1 and a.attnum > 0 and not a.attisdropped and c.relkind in ('r', 'v')
    order by c.relname, a.attnum`, [SCHEMA])).rows

const fks = (await db.query(
  `select con.conname as name, c.relname as table, rc.relname as ref_table,
          array(select a.attname from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k) as cols,
          array(select a.attname from unnest(con.confkey) k join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k) as ref_cols,
          exists (select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique and i.indpred is null
                  and (select array_agg(x order by x) from unnest(i.indkey::int2[]) x) = (select array_agg(x order by x) from unnest(con.conkey) x)) as one_to_one
     from pg_constraint con join pg_class c on c.oid = con.conrelid join pg_namespace n on n.oid = c.relnamespace
     join pg_class rc on rc.oid = con.confrelid join pg_namespace rn on rn.oid = rc.relnamespace
    where con.contype = 'f' and n.nspname = $1 and rn.nspname = $1 order by con.conname`, [SCHEMA])).rows

const fns = (await db.query(
  `select p.proname as name, p.proretset as retset, rt.typname as ret, rt.typtype as rettype_kind,
          p.pronargdefaults as ndefaults,
          coalesce(p.proargnames, '{}') as argnames, coalesce(p.proargmodes::text[], '{}') as argmodes,
          array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality as u(o, ord) join pg_type t on t.oid = u.o order by u.ord) as argtypes,
          p.pronargs as nargs
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
    where n.nspname = $1 and p.prokind = 'f' and rt.typname <> 'trigger'
    order by p.proname`, [SCHEMA])).rows

const tableRowType = new Map()
for (const t of tables) tableRowType.set(t.name, t)

const out = []
out.push(`// Generated by scripts/gen-db-types.mjs — do not edit by hand.`)
out.push(`// Run \`npm run db:types\` after changing supabase/migrations.`)
out.push(``)
out.push(`export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]`)
out.push(``)
out.push(`export type Database = {`)
out.push(`  __InternalSupabase: { PostgrestVersion: "12" }`)
out.push(`  public: {`)
for (const kind of ['r', 'v']) {
  const group = tables.filter((t) => t.kind === kind)
  if (!group.length) {
    out.push(`    ${kind === 'r' ? 'Tables' : 'Views'}: { [_ in never]: never }`)
    continue
  }
  out.push(`    ${kind === 'r' ? 'Tables' : 'Views'}: {`)
  for (const t of group) {
    const cols = columns.filter((c) => c.table === t.name)
    out.push(`      ${t.name}: {`)
    out.push(`        Row: {`)
    for (const c of cols) out.push(`          ${c.name}: ${tsType(c.udt)}${c.notnull ? '' : ' | null'}`)
    out.push(`        }`)
    if (kind === 'r') {
      out.push(`        Insert: {`)
      for (const c of cols) {
        if (c.generated === 's' || c.identity === 'a') { out.push(`          ${c.name}?: never`); continue }
        const optional = !c.notnull || c.hasdef || c.identity === 'd'
        out.push(`          ${c.name}${optional ? '?' : ''}: ${tsType(c.udt)}${c.notnull ? '' : ' | null'}`)
      }
      out.push(`        }`)
      out.push(`        Update: {`)
      for (const c of cols) {
        if (c.generated === 's' || c.identity === 'a') { out.push(`          ${c.name}?: never`); continue }
        out.push(`          ${c.name}?: ${tsType(c.udt)}${c.notnull ? '' : ' | null'}`)
      }
      out.push(`        }`)
    }
    out.push(`        Relationships: [`)
    for (const fk of fks.filter((f) => f.table === t.name)) {
      out.push(`          {`)
      out.push(`            foreignKeyName: "${fk.name}"`)
      out.push(`            columns: [${fk.cols.map((c) => `"${c}"`).join(', ')}]`)
      out.push(`            isOneToOne: ${fk.one_to_one}`)
      out.push(`            referencedRelation: "${fk.ref_table}"`)
      out.push(`            referencedColumns: [${fk.ref_cols.map((c) => `"${c}"`).join(', ')}]`)
      out.push(`          },`)
    }
    out.push(`        ]`)
    out.push(`      }`)
  }
  out.push(`    }`)
}

out.push(`    Functions: {`)
const seen = new Set()
for (const f of fns) {
  if (seen.has(f.name)) continue
  seen.add(f.name)
  const modes = f.argmodes.length ? f.argmodes : f.argtypes.map(() => 'i')
  const inArgs = []
  const outCols = []
  f.argtypes.forEach((typ, i) => {
    const mode = modes[i] ?? 'i'
    const name = f.argnames[i] || `arg${i}`
    if (mode === 'i' || mode === 'b') inArgs.push({ name, typ })
    if (mode === 'o' || mode === 't' || mode === 'b') outCols.push({ name, typ })
  })
  const firstOptional = inArgs.length - f.ndefaults
  out.push(`      ${f.name}: {`)
  if (inArgs.length === 0) out.push(`        Args: never`)
  else {
    out.push(`        Args: {`)
    inArgs.forEach((a, i) => out.push(`          ${a.name}${i >= firstOptional ? '?' : ''}: ${tsType(a.typ)} | null`))
    out.push(`        }`)
  }
  let ret
  if (outCols.length) ret = `{ ${outCols.map((c) => `${c.name}: ${tsType(c.typ)}`).join('; ')} }`
  else if (f.rettype_kind === 'c' && tableRowType.has(f.ret)) ret = `Database["public"]["Tables"]["${f.ret}"]["Row"]`
  else ret = tsType(f.ret)
  out.push(`        Returns: ${ret}${f.retset ? '[]' : ''}`)
  out.push(`      }`)
}
out.push(`    }`)
out.push(`    Enums: {`)
for (const e of enums) out.push(`      ${e.name}: ${e.labels.map((l) => `"${l}"`).join(' | ')}`)
out.push(`    }`)
out.push(`    CompositeTypes: { [_ in never]: never }`)
out.push(`  }`)
out.push(`}`)
out.push(``)
out.push(`type PublicSchema = Database["public"]`)
out.push(`export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]`)
out.push(`export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]`)
out.push(`export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]`)
out.push(`export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]`)
out.push(``)
out.push(`export const Constants = {`)
out.push(`  public: {`)
out.push(`    Enums: {`)
for (const e of enums) out.push(`      ${e.name}: [${e.labels.map((l) => `"${l}"`).join(', ')}],`)
out.push(`    },`)
out.push(`  },`)
out.push(`} as const`)
out.push(``)

writeFileSync(path.join(root, 'src/types/database.ts'), out.join('\n'))
console.log(`Wrote src/types/database.ts (${tables.length} tables, ${seen.size} functions, ${enums.length} enums)`)
await db.close()
