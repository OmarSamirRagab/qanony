import {
  Banknote,
  Briefcase,
  Building,
  Building2,
  FilePlus2,
  FileSignature,
  Gavel,
  Globe,
  HandCoins,
  Handshake,
  HeartCrack,
  HeartHandshake,
  KeyRound,
  Landmark,
  Lightbulb,
  Plane,
  Receipt,
  Scale,
  ScrollText,
  ShieldAlert,
  ShieldCheck,
  Store,
  Umbrella,
  Users,
  type LucideIcon,
} from 'lucide-react'

const ICONS: Record<string, LucideIcon> = {
  gavel: Gavel,
  scale: Scale,
  users: Users,
  'heart-crack': HeartCrack,
  'heart-handshake': HeartHandshake,
  'scroll-text': ScrollText,
  'building-2': Building2,
  'key-round': KeyRound,
  briefcase: Briefcase,
  store: Store,
  building: Building,
  'file-plus-2': FilePlus2,
  receipt: Receipt,
  lightbulb: Lightbulb,
  landmark: Landmark,
  'shield-check': ShieldCheck,
  'file-signature': FileSignature,
  'hand-coins': HandCoins,
  umbrella: Umbrella,
  'shield-alert': ShieldAlert,
  banknote: Banknote,
  handshake: Handshake,
  plane: Plane,
  globe: Globe,
}

export function CategoryIcon({ name, className }: { name: string | null | undefined; className?: string }) {
  const Icon = (name && ICONS[name]) || Scale
  return <Icon className={className} aria-hidden />
}
